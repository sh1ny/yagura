// Embeds schemas/plugin-manifest.v1.json into lib/src/manifest_schema.g.dart so
// the loader works without the repository checkout (for example in a compiled
// `yagura` binary). A test fails when the embedded copy is out of date.
//
// Usage, from packages/yagura_plugin: dart run tool/embed_schema.dart
import 'dart:io';

import 'package:path/path.dart' as p;

void main() {
  final package = Directory.current.path;
  final schema = File(
    p.join(package, '..', '..', 'schemas', 'plugin-manifest.v1.json'),
  ).readAsStringSync();
  if (schema.contains("'''")) {
    throw StateError("The schema must not contain ''' (raw string quoting).");
  }
  File(p.join(package, 'lib', 'src', 'manifest_schema.g.dart'))
    ..createSync(recursive: true)
    ..writeAsStringSync(
      '// GENERATED by tool/embed_schema.dart from '
      'schemas/plugin-manifest.v1.json. Do not edit.\n'
      '\n'
      '/// The manifest JSON Schema, version 1.\n'
      "const manifestSchemaV1 = r'''\n$schema''';\n",
    );
}
