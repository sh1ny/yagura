// Embeds lib/src/steam/patterns.yaml into lib/src/steam/patterns.g.dart so the
// daemon reads the SteamCMD output patterns without the repository checkout
// (for example in a compiled binary). A test fails when the embedded copy is
// out of date.
//
// Usage, from apps/yagurad: dart run tool/embed_steam_patterns.dart
import 'dart:io';

import 'package:path/path.dart' as p;

void main() {
  final package = Directory.current.path;
  final source = File(p.join(package, 'lib', 'src', 'steam', 'patterns.yaml'))
      .readAsStringSync();
  if (source.contains("'''")) {
    throw StateError(
      "patterns.yaml must not contain ''' (raw string quoting).",
    );
  }
  File(p.join(package, 'lib', 'src', 'steam', 'patterns.g.dart'))
    ..createSync(recursive: true)
    ..writeAsStringSync(
      '// GENERATED by tool/embed_steam_patterns.dart from '
      'lib/src/steam/patterns.yaml. Do not edit.\n'
      '\n'
      '/// The SteamCMD output pattern table.\n'
      "const steamPatternsYaml = r'''\n$source''';\n",
    );
}
